  await t.goto('http://localhost:8767/kundadmin/?demo'); await t.p.waitForSelector('.side');
  await t.card(t.LOGO + '<h1>Så ändrar ni er <span class="hl">hemsida</span></h1><p>Adminpanelen på dittforetag.se/admin – inga tekniska kunskaper behövs.</p><ol><li>Översikt</li><li>Ändra texter och bilder</li><li>AI-assistenten</li><li>Förfrågningar</li><li>Projekt och tjänster</li><li>Inställningar</li></ol>', 3600);
