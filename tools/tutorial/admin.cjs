  await t.say('1', 'Översikten visar nya förfrågningar, besökare och vad som väntar på dig.');
  await t.ring('.kpis', 8); await t.sleep(2000); await t.unring();
  await t.say('2', 'Under Sidor och texter ser du din hemsida. Klicka på en text och skriv.');
  await t.click('[data-v=sidor]'); await t.p.waitForSelector('.field'); await t.sleep(900);
  const f = t.p.frameLocator('#pf'); const box = await t.p.locator('#pf').boundingBox();
  const h = await f.locator('h1[data-es]').boundingBox(); if (h) await t.move([box.x + h.x + 80, box.y + h.y + 20]);
  await f.locator('h1[data-es]').click(); await t.p.keyboard.press('Control+A'); await t.p.keyboard.type('Vi bygger ditt drömhem – i tid', { delay: 45 }); await t.sleep(700);
  await t.say('2', 'Byt bild med ett klick – och tryck Publicera när du är nöjd.');
  await t.click('.field [data-img]'); await t.p.waitForSelector('.modal'); await t.sleep(500); await t.click('.modal [data-u] >> nth=1'); await t.sleep(700);
  await t.click('#pub'); await t.sleep(1500);
  await t.say('3', 'Eller skriv vad du vill i rutan högst upp – AI-assistenten föreslår ändringen.');
  await t.type('#aq', 'Ändra öppettider till mån–fre 7–17', 40); await t.click('#af button'); await t.p.waitForSelector('.act'); await t.sleep(900);
  await t.click('.act .btn'); await t.sleep(1200);
