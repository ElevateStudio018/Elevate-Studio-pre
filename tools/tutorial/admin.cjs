  await t.click('[data-v=forfragningar]'); await t.p.waitForSelector('.lead'); await t.sleep(900);
  await t.click('.lead >> nth=1'); await t.sleep(700); await t.click('#ls'); await t.p.selectOption('#ls', 'answered'); await t.sleep(1000);
  await t.say('5', 'Lägg till ett projekt med namn, ort och bild.');
